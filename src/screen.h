inline void screen_draw_char(int x, int y, char c, uint16_t color, uint8_t size) {
    if (c < 32 || c > 127) c = 32;
    c -= 32;
    uint16_t col = fixColor(color);
    
    for (int row = 0; row < 5; row++) {
        uint8_t line = font5x7[(uint8_t)c][row];
        for (int col_bit = 0; col_bit < 7; col_bit++) {
            if (line & (1 << (6 - col_bit))) {
                int draw_y = y + (6 - col_bit) * size;
                for (int sx = 0; sx < size; sx++) {
                    for (int sy = 0; sy < size; sy++) {
                        tft.drawPixel(x + row * size + sx, draw_y + sy, col);
                    }
                }
            }
        }
    }
}

inline void drawtext(int x, int y, const char *str, uint16_t color, uint8_t size = 1) {
    while (*str) {
        screen_draw_char(x, y, *str, color, size);
        x += 6 * size;
        str++;
    }
}

inline void screen_init(uint8_t rotation = 0) {
    tft.init();
    tft.setRotation(0);
    tft.fillScreen(fixColor(COLOR_BLACK));
}

inline void fillscreen(uint16_t color) {
    tft.fillScreen(fixColor(color));
}

inline void fillrect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t color) {
    tft.fillRect(x, y, w, h, fixColor(color));
    yield();
}

inline void drawrect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t color) {
    tft.drawRect(x, y, w, h, fixColor(color));
}

inline void drawcircle(int32_t x, int32_t y, int32_t r, uint16_t color) {
    tft.drawCircle(x, y, r, fixColor(color));
}

inline void fillcircle(int32_t x, int32_t y, int32_t r, uint16_t color) {
    tft.fillCircle(x, y, r, fixColor(color));
}

inline void drawline(int32_t x1, int32_t y1, int32_t x2, int32_t y2, uint16_t color) {
    tft.drawLine(x1, y1, x2, y2, fixColor(color));
}

inline void drawpixel(int32_t x, int32_t y, uint16_t color) {
    tft.drawPixel(x, y, fixColor(color));
}

